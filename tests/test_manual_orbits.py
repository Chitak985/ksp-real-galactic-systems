"""Manual placement, physical frame recovery, cosmology and hierarchy isolation."""
import copy
import math
from pathlib import Path
import re
import unittest

import rebuild_manual_orbits as manual
from rebuild_configs import CatalogError,ICRS_TO_GALACTIC,PARSEC_M,load_catalog,node_contents,orbit_position

ROOT=Path(__file__).resolve().parents[1]


def read_orbit(text):
    values=dict(re.findall(r"(?m)^\s*(\w+)\s*=\s*([^\r\n]+)",node_contents(text,"Orbit")))
    return {k:v.strip() if k in {"referenceBody","mode"} else float(v) for k,v in values.items()
            if k not in {"color","nodeColor","cameraSmaRatioBounds"}}


class ManualOrbitTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.catalog=load_catalog(ROOT/manual.CATALOG)
        cls.records={r["body_name"]:r for r in cls.catalog["objects"]}

    def test_every_manual_body_is_covered_once_and_stock_sun_is_excluded(self):
        found=set()
        for path in (ROOT/"RealGalacticSystems").rglob("*.cfg"):
            text=path.read_text(encoding="utf-8-sig")
            if text.startswith("// Generated by rebuild_") or not re.search(r"(?m)^\s*Body\s*\n",text):continue
            body=node_contents(text,"Body")
            found.add(re.search(r"(?m)^\s*name\s*=\s*([^\r\n]+)",body)[1].strip())
        self.assertEqual(found,set(self.records))
        self.assertEqual(len(found),12)
        self.assertNotIn("Sun",found)

    def test_frozen_orbits_recover_all_positions_and_never_move(self):
        for name,record in self.records.items():
            text=(ROOT/record["path"]).read_text(encoding="utf-8-sig")
            orbit=read_orbit(text)
            self.assertEqual(orbit["referenceBody"],"Sun")
            self.assertEqual(orbit["period"],3e300)
            self.assertEqual(orbit["mode"],"OFF")
            self.assertEqual(orbit["eccentricity"],0)
            self.assertEqual(orbit["epoch"],0)
            expected,_=manual.placement(record,self.catalog["settings"])
            actual=orbit_position(orbit)
            scale=math.hypot(*expected)
            with self.subTest(body=name):
                self.assertLess(math.dist(tuple(v/scale for v in actual),tuple(v/scale for v in expected)),2e-14)
                self.assertEqual(orbit_position(orbit,1e15),actual)

    def test_sky_coordinates_recover_in_icrs_and_galactic_frames(self):
        for name,record in self.records.items():
            position=record["position"]
            if position["kind"]=="preserved_orbit":continue
            xyz,_=manual.placement(record,self.catalog["settings"])
            if position["kind"]=="galactic_distance":
                lon=math.degrees(math.atan2(xyz[1],xyz[0]))%360
                lat=math.degrees(math.atan2(xyz[2],math.hypot(xyz[0],xyz[1])))
                self.assertAlmostEqual(lon,position["longitude_deg"],places=10)
                self.assertAlmostEqual(lat,position["latitude_deg"],places=10)
            else:
                icrs=[sum(ICRS_TO_GALACTIC[j][i]*xyz[j] for j in range(3)) for i in range(3)]
                ra=math.degrees(math.atan2(icrs[1],icrs[0]))%360
                dec=math.degrees(math.atan2(icrs[2],math.hypot(icrs[0],icrs[1])))
                self.assertAlmostEqual(ra,position["ra_deg"],places=10)
                self.assertAlmostEqual(dec,position["dec_deg"],places=10)

    def test_high_redshift_uses_comoving_distance_with_separate_lookback(self):
        for name in ("GN-z11","JADES-GS-Z14-0"):
            record=self.records[name];xyz,d=manual.placement(record,self.catalog["settings"])
            self.assertAlmostEqual(math.hypot(*xyz)/(d["placement_mpc"]*1e6*PARSEC_M),1,places=14)
            self.assertGreater(d["placement_mpc"],9000)
            self.assertLess(d["placement_mpc"],11000)
            self.assertGreater(d["lookback_years"],13e9)
            self.assertLess(d["lookback_years"],13.8e9)
            self.assertGreater(d["placement_mpc"]/d["angular_diameter_mpc"],11)
            self.assertGreater(d["luminosity_mpc"]/d["placement_mpc"],11)

    def test_unknown_preserves_its_original_fictional_location(self):
        record=self.records["unknown"]
        xyz,_=manual.placement(record,self.catalog["settings"])
        self.assertEqual(xyz,orbit_position(record["position"]["original_orbit"],0))
        self.assertEqual(record["core_soi_m"],1e10)

    def test_compact_sois_cannot_enclose_sol_or_other_manual_cores(self):
        points=[]
        for name,r in self.records.items():
            xyz,_=manual.placement(r,self.catalog["settings"])
            soi=r["core_soi_m"]
            actual=float(re.search(r"(?m)^\s*sphereOfInfluence\s*=\s*(\S+)",node_contents((ROOT/r["path"]).read_text(),"Properties"))[1])
            self.assertEqual(actual,soi)
            self.assertLess(soi,math.hypot(*xyz))
            for old_name,old_xyz,old_soi in points:
                self.assertGreater(math.dist(xyz,old_xyz),soi+old_soi,(name,old_name))
            points.append((name,xyz,soi))

    def test_rebuild_is_idempotent_and_rejects_identity_or_generated_targets(self):
        outputs=manual.build_updates(self.catalog,ROOT)
        for path,text in outputs.items():self.assertEqual(text,path.read_bytes().decode("utf-8"))
        record=copy.deepcopy(self.records["SagittariusA"])
        record["body_name"]="Sun"
        with self.assertRaises(CatalogError):manual.update_config(outputs[ROOT/self.records["SagittariusA"]["path"]],record,self.catalog["settings"])
        record=copy.deepcopy(self.records["SagittariusA"])
        record["path"]="RealGalacticSystems/Systems/ngc_300.cfg"
        with self.assertRaises(CatalogError):manual.build_updates(dict(self.catalog,objects=[record]),ROOT)
        record=copy.deepcopy(self.records["SagittariusA"])
        record["position"]["frame"]="Galactic"
        with self.assertRaises(CatalogError):manual.placement(record,self.catalog["settings"])


if __name__=="__main__":unittest.main()
